def _fernet() -> Fernet:
    # Derive a stable 32-byte key from the administrator token secret.
    # The secret must be changed from the development default in production.
    digest = hashlib.sha256(TOKEN_SECRET.encode("utf-8")).digest()
    return Fernet(base64.urlsafe_b64encode(digest))


def _encrypt(value: str) -> str:
    return _fernet().encrypt(value.encode("utf-8")).decode("ascii")


def _decrypt(value: str) -> str:
    try:
        return _fernet().decrypt(value.encode("ascii")).decode("utf-8")
    except (InvalidToken, ValueError) as exc:
        raise HTTPException(status_code=500, detail="Stored server password cannot be decrypted; verify TCCS_ADMIN_TOKEN_SECRET") from exc


async def ensure_server_schema(db: AsyncSession) -> None:
    await db.execute(text("""
        CREATE TABLE IF NOT EXISTS asterisk_servers (
            id BIGSERIAL PRIMARY KEY,
            name VARCHAR(64) NOT NULL,
            role VARCHAR(16) NOT NULL DEFAULT 'PRIMARY',
            ip_address VARCHAR(64) NOT NULL UNIQUE,
            ssh_username VARCHAR(64) NOT NULL DEFAULT 'root',
            ssh_password_encrypted TEXT NOT NULL,
            ssh_port INTEGER NOT NULL DEFAULT 22,
            enabled BOOLEAN NOT NULL DEFAULT TRUE,
            last_sync_at TIMESTAMPTZ,
            last_sync_status VARCHAR(32),
            last_sync_message TEXT,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
    """))
    await db.execute(text("CREATE INDEX IF NOT EXISTS idx_asterisk_servers_role ON asterisk_servers(role)"))
    await db.commit()


async def _query_config_data(db: AsyncSession) -> Dict[str, Any]:
    sections = [dict(r._mapping) for r in (await db.execute(text("SELECT id,code,name,enabled FROM sections ORDER BY id"))).all()]
    stations = [dict(r._mapping) for r in (await db.execute(text("SELECT id,station_number,name,location,section_id,sip_extension,station_type,enabled,priority FROM stations ORDER BY priority,station_number"))).all()]
    controllers = [dict(r._mapping) for r in (await db.execute(text("""
        SELECT c.id,c.code,c.name,c.section_id,c.enabled,c.sip_account_id,
               sa.extension AS sip_extension,sa.username AS sip_username,sa.password AS sip_password,
               sa.enabled AS sip_enabled
        FROM controllers c LEFT JOIN sip_accounts sa ON sa.id=c.sip_account_id
        ORDER BY c.code
    """))).all()]
    groups = [dict(r._mapping) for r in (await db.execute(text("""
        SELECT g.id,g.code,g.name,g.section_id,g.enabled,
               COALESCE(json_agg(gm.station_id ORDER BY gm.station_id) FILTER (WHERE gm.station_id IS NOT NULL),'[]'::json) AS member_ids
        FROM station_groups g LEFT JOIN station_group_members gm ON gm.group_id=g.id
        GROUP BY g.id ORDER BY g.code
    """))).all()]
    return {"sections": sections, "stations": stations, "controllers": controllers, "groups": groups}


def _safe(value: Any) -> str:
    return str(value or "").replace("\n", " ").replace("\r", " ").strip()


def _generate_pjsip(data: Dict[str, Any]) -> str:
    lines = [
        "; TCCS MANAGED PJSIP CONFIGURATION",
        "; Generated by TCCS Server Management. Do not edit manually.",
        "; Generated at " + datetime.now(timezone.utc).isoformat(),
        "",
        "[transport-tccs]",
        "type=transport",
        "protocol=udp",
        "bind=0.0.0.0:5060",
        "",
        "[station-template](!)",
        "type=endpoint",
        "transport=transport-tccs",
        "context=tccs-stations",
        "disallow=all",
        "allow=alaw,ulaw",
        "direct_media=no",
        "rtp_symmetric=yes",
        "force_rport=yes",
        "rewrite_contact=yes",
        "",
        "[station-auth-template](!)",
        "type=auth",
        "auth_type=userpass",
        "",
        "[station-aor-template](!)",
        "type=aor",
        "max_contacts=1",
        "remove_existing=yes",
        "qualify_frequency=30",
        "",
    ]
    for station in data["stations"]:
        if not station["enabled"]:
            continue
        ext = _safe(station["sip_extension"])
        caller = f'{_safe(station["station_number"])} {_safe(station["name"])}'.strip()
        # Station passwords are not currently part of station master data. Keep the
        # same explicit placeholder convention used by the baseline configuration.
        password = "CHANGE-ME-" + ext
        lines += [
            f"[{ext}](station-template)",
            f"aors={ext}",
            f"auth={ext}-auth",
            f'callerid="{caller}" <{ext}>',
            "",
            f"[{ext}-auth](station-auth-template)",
            f"username={ext}",
            f"password={password}",
            "",
            f"[{ext}](station-aor-template)",
            "",
        ]

    for controller in data["controllers"]:
        if not controller["enabled"] or not controller.get("sip_extension") or not controller.get("sip_enabled", True):
            continue
        ext = _safe(controller["sip_extension"])
        username = _safe(controller.get("sip_username") or ext)
        password = _safe(controller.get("sip_password"))
        if not password:
            continue
        lines += [
            f"; Controller: {_safe(controller['code'])} - {_safe(controller['name'])}",
            f"[{ext}](station-template)",
            f"aors={ext}",
            f"auth={ext}-auth",
            f'callerid="{_safe(controller["name"])}" <{ext}>',
            "",
            f"[{ext}-auth](station-auth-template)",
            f"username={username}",
            f"password={password}",
            "",
            f"[{ext}](station-aor-template)",
            "",
        ]
    return "\n".join(lines) + "\n"


def _generate_extensions(data: Dict[str, Any]) -> str:
    lines = [
        "; TCCS MANAGED DIALPLAN CONFIGURATION",
        "; Generated by TCCS Server Management. Do not edit manually.",
        "; Generated at " + datetime.now(timezone.utc).isoformat(),
        "",
        "[tccs-stations]",
        "exten => 900,1,NoOp(TCCS station joining ${TCCS_CONFERENCE})",
        " same => n,Answer()",
        " same => n,ExecIf($[\"${TCCS_CONFERENCE}\"=\"\"]?Hangup())",
        " same => n,ConfBridge(${TCCS_CONFERENCE},tccs_bridge,tccs_station)",
        " same => n,Hangup()",
        "",
        "exten => _10XX,1,NoOp(TCCS station call to ${EXTEN})",
        " same => n,Dial(PJSIP/${EXTEN},30)",
        " same => n,Hangup()",
        "",
    ]
    for controller in data["controllers"]:
        if not controller["enabled"] or not controller.get("sip_extension"):
            continue
        ext = _safe(controller["sip_extension"])
        lines += [
            f"; Controller {_safe(controller['code'])}: {ext}",
            f"exten => {ext},1,NoOp(TCCS station ${'{'}CALLERID(num){'}'} joining controller {ext})",
            " same => n,Answer()",
            f" same => n,Set(TCCS_CONFERENCE=TCCS-CTRL-{ext})",
            " same => n,ConfBridge(${TCCS_CONFERENCE},tccs_bridge,tccs_station)",
            " same => n,Hangup()",
            "",
        ]
    # Preserve the standard controller extension used by the current Stage 2 browser.
    if not any(_safe(c.get("sip_extension")) == "9999" for c in data["controllers"]):
        lines += [
            "; Default Stage 2 browser controller conference entry",
            "exten => 9999,1,NoOp(TCCS browser controller joining SECTION01)",
            " same => n,Answer()",
            " same => n,ConfBridge(SECTION01,tccs_bridge,tccs_controller)",
            " same => n,Hangup()",
            "",
        ]
    lines += [
        "; Direct station-to-controller dialing",
        "exten => _9XXX,1,NoOp(TCCS station ${CALLERID(num)} joining controller ${EXTEN})",
        " same => n,Answer()",
        " same => n,Set(TCCS_CONFERENCE=TCCS-CTRL-${EXTEN})",
        " same => n,ConfBridge(${TCCS_CONFERENCE},tccs_bridge,tccs_station)",
        " same => n,Hangup()",
        "",
    ]
    return "\n".join(lines)


