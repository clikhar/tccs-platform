@router.post("")
async def create_server(payload: dict = Body(...), db: AsyncSession = Depends(get_db), admin: dict = Depends(require_admin)):
    await ensure_server_schema(db)
    name = _safe(payload.get("name")) or "Asterisk Server"
    role = _safe(payload.get("role") or "PRIMARY").upper()
    ip = _safe(payload.get("ip_address"))
    username = _safe(payload.get("ssh_username") or "root")
    password = str(payload.get("ssh_password") or "")
    port = int(payload.get("ssh_port") or 22)
    if role not in {"PRIMARY", "STANDBY"}:
        raise HTTPException(400, "Server role must be PRIMARY or STANDBY")
    if not ip or len(ip) > 64:
        raise HTTPException(400, "Asterisk server IP address is required")
    if not username or not password:
        raise HTTPException(400, "SSH username and password are required")
    if port < 1 or port > 65535:
        raise HTTPException(400, "Invalid SSH port")
    if role == "PRIMARY":
        await db.execute(text("UPDATE asterisk_servers SET role='STANDBY' WHERE role='PRIMARY'"))
    try:
        result = await db.execute(text("""
            INSERT INTO asterisk_servers(name,role,ip_address,ssh_username,ssh_password_encrypted,ssh_port,enabled,updated_at)
            VALUES(:name,:role,:ip,:username,:password,:port,:enabled,NOW())
            RETURNING id,name,role,ip_address,ssh_username,ssh_port,enabled,last_sync_at,last_sync_status,last_sync_message
        """), {"name": name[:64], "role": role, "ip": ip, "username": username[:64], "password": _encrypt(password), "port": port, "enabled": bool(payload.get("enabled", True))})
        await db.commit()
        return dict(result.first()._mapping)
    except Exception as exc:
        await db.rollback()
        if "duplicate" in str(exc).lower() or "unique" in str(exc).lower():
            raise HTTPException(409, "A server with this IP address already exists")
        raise


@router.put("/{server_id}")
async def update_server(server_id: int, payload: dict = Body(...), db: AsyncSession = Depends(get_db), admin: dict = Depends(require_admin)):
    await ensure_server_schema(db)
    current = (await db.execute(text("SELECT * FROM asterisk_servers WHERE id=:id"), {"id": server_id})).first()
    if current is None:
        raise HTTPException(404, "Asterisk server not found")
    name = _safe(payload.get("name", current.name)) or current.name
    role = _safe(payload.get("role", current.role)).upper()
    ip = _safe(payload.get("ip_address", current.ip_address))
    username = _safe(payload.get("ssh_username", current.ssh_username)) or current.ssh_username
    password = str(payload.get("ssh_password") or "")
    encrypted = current.ssh_password_encrypted if not password else _encrypt(password)
    port = int(payload.get("ssh_port", current.ssh_port) or 22)
    if role not in {"PRIMARY", "STANDBY"} or not ip or port < 1 or port > 65535:
        raise HTTPException(400, "Invalid server configuration")
    if role == "PRIMARY":
        await db.execute(text("UPDATE asterisk_servers SET role='STANDBY' WHERE role='PRIMARY' AND id<>:id"), {"id": server_id})
    try:
        result = await db.execute(text("""
            UPDATE asterisk_servers SET name=:name,role=:role,ip_address=:ip,ssh_username=:username,ssh_password_encrypted=:password,ssh_port=:port,enabled=:enabled,updated_at=NOW()
            WHERE id=:id
            RETURNING id,name,role,ip_address,ssh_username,ssh_port,enabled,last_sync_at,last_sync_status,last_sync_message
        """), {"id": server_id, "name": name[:64], "role": role, "ip": ip, "username": username[:64], "password": encrypted, "port": port, "enabled": bool(payload.get("enabled", current.enabled))})
        await db.commit()
        return dict(result.first()._mapping)
    except Exception as exc:
        await db.rollback()
        if "duplicate" in str(exc).lower() or "unique" in str(exc).lower():
            raise HTTPException(409, "A server with this IP address already exists")
        raise


@router.delete("/{server_id}")
async def delete_server(server_id: int, db: AsyncSession = Depends(get_db), admin: dict = Depends(require_admin)):
    await ensure_server_schema(db)
    result = await db.execute(text("DELETE FROM asterisk_servers WHERE id=:id RETURNING id"), {"id": server_id})
