@router.post("/{server_id}/sync")
async def sync_server(server_id: int, db: AsyncSession = Depends(get_db), admin: dict = Depends(require_admin)):
    await ensure_server_schema(db)
    row = (await db.execute(text("SELECT * FROM asterisk_servers WHERE id=:id AND enabled=TRUE"), {"id": server_id})).first()
    if row is None:
        raise HTTPException(404, "Enabled Asterisk server not found")
    server = dict(row._mapping)
    data = await _query_config_data(db)
    files = {PJSIP_FILE: _generate_pjsip(data), EXTENSIONS_FILE: _generate_extensions(data), CONFBRIDGE_FILE: _generate_confbridge(data)}
    try:
        result = await _run_sync(server, files)
        await db.execute(text("UPDATE asterisk_servers SET last_sync_at=NOW(),last_sync_status='SYNCED',last_sync_message=:message,updated_at=NOW() WHERE id=:id"), {"id": server_id, "message": result["message"]})
        await db.commit()
        return {"status": "SYNCED", "server_id": server_id, "files": list(files.keys()), "message": result["message"]}
    except Exception as exc:
        message = str(exc)
        await db.execute(text("UPDATE asterisk_servers SET last_sync_at=NOW(),last_sync_status='FAILED',last_sync_message=:message,updated_at=NOW() WHERE id=:id"), {"id": server_id, "message": message[:2000]})
        await db.commit()
        raise HTTPException(502, f"Configuration sync failed: {message}")


@router.post("/sync-all")
async def sync_all(db: AsyncSession = Depends(get_db), admin: dict = Depends(require_admin)):
    await ensure_server_schema(db)
    result = await db.execute(text("SELECT * FROM asterisk_servers WHERE enabled=TRUE ORDER BY id"))
    servers = [dict(r._mapping) for r in result]
    data = await _query_config_data(db)
    files = {PJSIP_FILE: _generate_pjsip(data), EXTENSIONS_FILE: _generate_extensions(data), CONFBRIDGE_FILE: _generate_confbridge(data)}
    results: List[Dict[str, Any]] = []
    for server in servers:
        try:
            response = await _run_sync(server, files)
            await db.execute(text("UPDATE asterisk_servers SET last_sync_at=NOW(),last_sync_status='SYNCED',last_sync_message=:message,updated_at=NOW() WHERE id=:id"), {"id": server["id"], "message": response["message"]})
            results.append({"id": server["id"], "name": server["name"], "status": "SYNCED", "message": response["message"]})
        except Exception as exc:
            message = str(exc)
            await db.execute(text("UPDATE asterisk_servers SET last_sync_at=NOW(),last_sync_status='FAILED',last_sync_message=:message,updated_at=NOW() WHERE id=:id"), {"id": server["id"], "message": message[:2000]})
            results.append({"id": server["id"], "name": server["name"], "status": "FAILED", "message": message})
    await db.commit()
    return {"status": "COMPLETED", "servers": results}


